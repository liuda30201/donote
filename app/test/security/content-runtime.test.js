'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const { loadContentKeyring } = require('../../src/security/runtime');
test('startup content keyring authenticates persisted records and rejects unsafe or reused keys', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dn-content-runtime-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const storageRoot = path.join(root, 'data'); fs.mkdirSync(storageRoot);
  const filename = path.join(root, 'content.json');
  const authKey = crypto.randomBytes(32);
  const config = { version: 1, activeKeyId: 'content-one', keys: { 'content-one': crypto.randomBytes(32).toString('base64') } };
  const save = value => fs.writeFileSync(filename, JSON.stringify(value), { mode: 0o600 });
  save(config);
  const ring = loadContentKeyring({ storageRoot, filename, authKey });
  const context = { userId: 'synthetic-user', messageId: 'synthetic-message' };
  const payload = ring.encrypt({ content: 'synthetic-secret', remark: '' }, context);
  assert.equal(ring.decrypt(payload, context).content, 'synthetic-secret');
  assert.throws(() => ring.decrypt(payload, { ...context, userId: 'other' }));
  ring.close();
  fs.chmodSync(filename, 0o644);
  assert.throws(() => loadContentKeyring({ storageRoot, filename, authKey }));
  fs.chmodSync(filename, 0o600);
  const link = path.join(root, 'linked.json'); fs.linkSync(filename, link);
  assert.throws(() => loadContentKeyring({ storageRoot, filename, authKey }));
  fs.unlinkSync(link);
  const internal = path.join(storageRoot, 'content.json'); fs.writeFileSync(internal, JSON.stringify(config), { mode: 0o600 });
  assert.throws(() => loadContentKeyring({ storageRoot, filename: internal, authKey }));
  save({ ...config, keys: { 'content-one': authKey.toString('base64') } });
  assert.throws(() => loadContentKeyring({ storageRoot, filename, authKey }));
  save({ ...config, activeKeyId: 'missing' });
  assert.throws(() => loadContentKeyring({ storageRoot, filename, authKey }));
  save({ ...config, unexpected: true });
  assert.throws(() => loadContentKeyring({ storageRoot, filename, authKey }));
  fs.writeFileSync(filename, Buffer.alloc(16385));
  assert.throws(() => loadContentKeyring({ storageRoot, filename, authKey }));
});
