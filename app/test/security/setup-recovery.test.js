'use strict';
const test = require('node:test'); const assert = require('node:assert/strict');
const fs = require('node:fs'); const os = require('node:os'); const path = require('node:path'); const crypto = require('node:crypto');
const { openDatabase } = require('../../src/db'); const { SECURITY_MIGRATION } = require('../../src/db/schema'); const { createRepositories } = require('../../src/db/repositories');
const p = require('../../src/security/primitives'); const { createAuthService } = require('../../src/security/auth-service');

test('restricted setup and recovery never mint sessions and consume challenges/codes once', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dn-setup-'));
  const db = openDatabase({ storageRoot: root, migrations: [SECURITY_MIGRATION] }); t.after(() => { db.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const repo = createRepositories(db); let at = 1800000000000;
  const service = createAuthService({ repo, allowedOrigins: ['https://test.local'], encryptionKey: crypto.randomBytes(32), keyId: 'test', now: () => at });
  const req = body => ({ body, headers: { origin: 'https://test.local' }, ip: '127.0.0.1' });
  const password = 'synthetic-password-old'; const newPassword = 'synthetic-password-new';
  const user = repo.createUser({ username: 'admin-setup', displayName: 'Setup', role: 'admin', mustChangePassword: true, passwordHash: await p.hashPassword(password) });
  const initial = await service.login(req({ username: user.username, password }));
  assert.equal(initial.requiresSetup, true); assert.equal(initial.requireFactor, true); assert.equal(initial.requirePassword, true);
  assert.throws(() => service.authenticateRequest({ headers: { cookie: `__Host-dn_session=${initial.challenge}` } }), /Authentication failed/);
  assert.throws(() => service.completeLogin(req({ challenge: initial.challenge, code: '123456' })));
  const staged = service.startSetup(req({ challenge: initial.challenge }));
  assert.match(staged.secret, /^[A-Z2-7]{32}$/);
  assert.throws(() => service.startSetup(req({ challenge: initial.challenge })));
  await assert.rejects(service.completeSetup(req({ challenge: staged.challenge, newPassword, code: 'bad' })));
  const done = await service.completeSetup(req({ challenge: staged.challenge, newPassword, code: p.generateTotp(staged.secret, { now: at }) }));
  assert.equal(done.requiresLogin, true); assert.equal(done.recoveryCodes.length, 10); assert.equal(done.token, undefined);
  assert.equal(repo.listSessions(user.id).length, 0);
  await assert.rejects(service.completeSetup(req({ challenge: staged.challenge, newPassword, code: p.generateTotp(staged.secret, { now: at }) })));
  assert.equal(repo.findUserById(user.id).must_change_password, 0);
  await assert.rejects(service.login(req({ username: user.username, password })));
  at += 60000;
  const login = await service.login(req({ username: user.username, password: newPassword }));
  const logged = service.completeLogin(req({ challenge: login.challenge, code: p.generateTotp(staged.secret, { now: at }) }));
  assert.equal(logged.user.id, user.id);
  const recovered = await service.startRecovery(req({ username: user.username, password: newPassword, recoveryCode: done.recoveryCodes[0] }));
  assert.equal(recovered.requiresSetup, true); assert.equal(recovered.requirePassword, true);
  assert.equal(repo.findSessionByToken(logged.token, at), null);
  assert.equal(repo.getTotpCredential(user.id), null);
  assert.equal(repo.findUserById(user.id).must_change_password, 1);
  assert.equal(repo.findUserById(user.id).login_policy, 'strict');
  const interrupted = await service.login(req({ username: user.username, password: newPassword }));
  assert.equal(interrupted.requiresSetup, true); assert.equal(interrupted.requireFactor, true);
  await assert.rejects(service.startRecovery(req({ username: user.username, password: newPassword, recoveryCode: done.recoveryCodes[0] })));
  const recoveryStaged = service.startSetup(req({ challenge: recovered.challenge }));
  const final = await service.completeSetup(req({ challenge: recoveryStaged.challenge, newPassword: 'synthetic-recovered-password', code: p.generateTotp(recoveryStaged.secret, { now: at }) }));
  assert.equal(final.requiresLogin, true); assert.equal(final.recoveryCodes.length, 10);
  assert.equal(repo.listSessions(user.id).filter(s => s.revoked_at === null).length, 0);
  at += 60000;
  const expired = await service.login(req({ username: user.username, password: 'synthetic-recovered-password' })); at += 300001;
  assert.throws(() => service.completeLogin(req({ challenge: expired.challenge, code: p.generateTotp(recoveryStaged.secret, { now: at }) })));
});
