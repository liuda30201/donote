'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const crypto = require('node:crypto');
const express = require('express');
const { openDatabase } = require('../../src/db');
const { ACCOUNT_MIGRATIONS } = require('../../src/db/schema');
const { createRepositories } = require('../../src/db/repositories');
const { createAuthService } = require('../../src/security/auth-service');
const { createEmailVerification } = require('../../src/security/email-verification');
const { createAuthRouter } = require('../../src/routes/auth');
async function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'registration-'));
  const db = openDatabase({ storageRoot: root, migrations: ACCOUNT_MIGRATIONS });
  t.after(() => { db.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const repo = createRepositories(db), key = crypto.randomBytes(32), sent = [];
  let at = Date.now();
  const service = createAuthService({ repo, encryptionKey: key, keyId: 'test', allowedOrigins: ['https://test.local'], now: () => at });
  const mailer = { available: true, async sendCode(m) { sent.push(m); } };
  const email = createEmailVerification({ repo, authService: service, mailer, encryptionKey: key, now: () => at });
  service.setEmailVerification(email);
  const body = { password: 'Strong-password-2026!', email: 'person@example.com' };
  const req = body => ({ body, ip: '127.0.0.1', headers: { origin: 'https://test.local' } });
  return { db, repo, service, email, mailer, sent, body, req, tick: (ms = 61000) => at += ms };
}
test('public registration verifies email before creating an ordinary password-only account; replay fails', async t => {
  const f = await fixture(t);
  const staged = await f.email.startRegistration(f.req(f.body));
  assert.equal(f.repo.findUserByEmail(f.body.email), null);
  assert.equal(JSON.stringify(staged).includes(f.sent[0].code), false);
  const stored = f.db.prepare('SELECT * FROM registration_challenges').get();
  assert.notEqual(stored.code_hash, f.sent[0].code);
  assert.notEqual(stored.password_hash, f.body.password);
  assert.equal(f.email.completeRegistration(f.req({ challenge: staged.challenge, code: f.sent[0].code })).success, true);
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: staged.challenge, code: f.sent[0].code })));
  const user = f.repo.findUserByEmail(f.body.email);
  assert.equal(user.role, 'user');
  assert.equal(f.repo.email.preference(user.id).method, 'password');
  assert.equal(f.repo.email.preference(user.id).email, f.body.email);
  assert.ok((await f.service.login(f.req({ email: f.body.email, password: f.body.password }))).token);
});
test('registration enforces origin, password policy, expiry, five malformed attempts, and delivery failure', async t => {
  const f = await fixture(t);
  await assert.rejects(f.email.startRegistration({ body: f.body, headers: { origin: 'https://evil.test' } }), { status: 403 });
  await assert.rejects(f.email.startRegistration(f.req({ ...f.body, password: 'short' })), { code: 'PASSWORD_POLICY' });
  const first = await f.email.startRegistration(f.req(f.body));
  for (let i = 0; i < 5; i++) assert.throws(() => f.email.completeRegistration(f.req({ challenge: first.challenge, code: 'bad' })));
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: first.challenge, code: f.sent[0].code })));
  f.tick();
  const second = await f.email.startRegistration(f.req(f.body));
  f.tick(300001);
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: second.challenge, code: f.sent.at(-1).code })));
  f.mailer.sendCode = async () => { throw new Error('smtp'); };
  await assert.rejects(f.email.startRegistration(f.req(f.body)), { code: 'MAIL_UNAVAILABLE' });
  assert.equal(f.repo.findUserByEmail(f.body.email), null);
});
test('registration challenges can be cancelled before editing credentials', async t => {
  const f = await fixture(t);
  const staged = await f.email.startRegistration(f.req(f.body));
  assert.ok(f.repo.email.findRegistration(staged.challenge, staged.expiresAt - 1));
  assert.deepEqual(f.email.cancelRegistration(f.req({ challenge: staged.challenge })), { success: true });
  assert.equal(f.repo.email.findRegistration(staged.challenge, staged.expiresAt - 1), null);
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: staged.challenge, code: f.sent[0].code })), { code: 'AUTH_FAILED' });
  const replacement = await f.email.startRegistration(f.req({ ...f.body, password: 'Changed-password-2026!' }));
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: staged.challenge, code: f.sent[0].code })), { code: 'AUTH_FAILED' });
  assert.equal(f.email.completeRegistration(f.req({ challenge: replacement.challenge, code: f.sent.at(-1).code })).success, true);
  const signedIn = await f.service.login(f.req({ email: f.body.email, password: 'Changed-password-2026!' }));
  assert.ok(signedIn.token);
  await assert.rejects(f.service.login(f.req({ email: f.body.email, password: f.body.password })));
});
test('duplicate identity is generic, cannot replace passwords, and concurrent starts are bounded', async t => {
  const f = await fixture(t);
  const first = await f.email.startRegistration(f.req(f.body));
  f.email.completeRegistration(f.req({ challenge: first.challenge, code: f.sent[0].code }));
  f.tick();
  const second = await f.email.startRegistration(f.req({ ...f.body, password: 'Replacement-password-2026!' }));
  assert.equal(f.email.completeRegistration(f.req({ challenge: second.challenge, code: f.sent.at(-1).code })).success, true);
  assert.ok((await f.service.login(f.req({ email: f.body.email, password: f.body.password }))).token);
  await assert.rejects(f.service.login(f.req({ email: f.body.email, password: 'Replacement-password-2026!' })));
  f.tick();
  const results = await Promise.allSettled([1, 2, 3].map(i => f.email.startRegistration(f.req({ ...f.body, email: `person${i}@example.com` }))));
  assert.equal(results.filter(r => r.status === 'rejected' && r.reason.code === 'AUTH_BUSY').length, 1);
});
test('registration transaction rolls back account and consumption if audit fails; resend invalidates old code', async t => {
  const f = await fixture(t);
  const first = await f.email.startRegistration(f.req(f.body));
  await assert.rejects(f.email.startRegistration(f.req(f.body)), { code: 'REGISTRATION_RATE_LIMIT' });
  f.tick();
  const next = await f.email.startRegistration(f.req(f.body));
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: first.challenge, code: f.sent[0].code })));
  const audit = f.repo.addAudit;
  f.repo.addAudit = () => { throw new Error('audit unavailable'); };
  assert.throws(() => f.email.completeRegistration(f.req({ challenge: next.challenge, code: f.sent[1].code })));
  assert.equal(f.repo.findUserByEmail(f.body.email), null);
  assert.ok(f.repo.email.findRegistration(next.challenge, next.expiresAt - 1));
  f.repo.addAudit = audit;
  assert.equal(f.email.completeRegistration(f.req({ challenge: next.challenge, code: f.sent[1].code })).success, true);
});
test('registration HTTP status, JSON, origin and cookie boundaries', async t => {
  const f = await fixture(t), app = express();
  app.use(express.json()); app.use('/api', createAuthRouter({ authService: f.service }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => server.close());
  const base = `http://127.0.0.1:${server.address().port}/api/auth`;
  assert.equal((await (await fetch(base + '/status')).json()).registration, true);
  assert.equal((await fetch(base + '/register/start', { method: 'POST' })).status, 415);
  const post = (route, body, origin = 'https://test.local') => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(body) });
  assert.equal((await post('/register/start', f.body, 'https://evil.test')).status, 403);
  const start = await post('/register/start', f.body);
  assert.equal(start.headers.get('set-cookie'), null);
  const staged = await start.json();
  const cancelled = await post('/register/cancel', { challenge: staged.challenge });
  assert.equal(cancelled.status, 200);
  assert.equal((await cancelled.json()).success, true);
  assert.equal((await post('/register/confirm', { challenge: staged.challenge, code: f.sent[0].code })).status, 401);
  const replacementResponse = await post('/register/start', f.body);
  const replacement = await replacementResponse.json();
  const confirm = await post('/register/confirm', { challenge: replacement.challenge, code: f.sent.at(-1).code });
  assert.equal(confirm.status, 200);
  assert.equal(confirm.headers.get('set-cookie'), null);
  f.mailer.available = false;
  assert.equal((await (await fetch(base + '/status')).json()).registration, false);
});
