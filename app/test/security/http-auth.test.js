'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'); const os = require('node:os'); const path = require('node:path');
const crypto = require('node:crypto'); const express = require('express');
const { openDatabase } = require('../../src/db');
const { SECURITY_MIGRATION } = require('../../src/db/schema');
const { createRepositories } = require('../../src/db/repositories');
const p = require('../../src/security/primitives');
const { createAuthService } = require('../../src/security/auth-service');
const { createAuthRouter } = require('../../src/routes/auth');
const { createSessionAuth } = require('../../src/middleware/auth');

test('HTTP session auth, CSRF, TOTP challenges and secure cookies', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'dn-auth-http-'));
  const db = openDatabase({ storageRoot: root, migrations: [SECURITY_MIGRATION] });
  const repo = createRepositories(db); const key = crypto.randomBytes(32); let at = 1800000000000;
  const password = 'synthetic-account-password'; const hash = await p.hashPassword(password);
  const user = repo.createUser({ username: 'ordinary', displayName: 'Ordinary', passwordHash: hash });
  const admin = repo.createUser({ username: 'administrator', displayName: 'Admin', passwordHash: hash, role: 'admin' });
  const factorUser = repo.createUser({ username: 'factor-user', displayName: 'Factor', passwordHash: hash });
  const secret = p.generateTotpSecret();
  repo.setPendingTotp({ userId: factorUser.id, encryptedSecret: JSON.stringify(p.encryptSecret(secret, key, { userId: factorUser.id, purpose: 'totp-secret', keyId: 'test' })) });
  repo.withTotpCounter({ userId: factorUser.id, counter: Math.floor(at / 30000) - 1, enroll: true, at }, () => true);
  const service = createAuthService({ repo, allowedOrigins: ['https://donote.test'], encryptionKey: key, keyId: 'test', now: () => at });
  const app = express(); app.use(express.json()); app.use('/api', createAuthRouter({ authService: service }));
  app.get('/private', createSessionAuth(service), (req, res) => res.json({ userId: req.userId }));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(() => { server.close(); db.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  async function request(route, body, headers = {}, method = body === undefined ? 'GET' : 'POST') {
    const res = await fetch(base + route, { method, headers: { ...(body === undefined ? {} : { 'Content-Type': 'application/json', Origin: 'https://donote.test' }), ...headers }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: res.status, body: await res.json(), headers: res.headers };
  }
  assert.equal((await request('/api/auth/login', { username: 'ordinary', password }, { Origin: 'https://evil.test' })).status, 403);
  assert.equal((await request('/api/auth/login', { username: 'ordinary', password: 'wrong-password' })).status, 401);
  assert.equal((await request('/api/auth/login', { username: 'missing-user', password })).status, 401);
  assert.equal((await request('/api/auth/login', { username: 'administrator', password })).body.requiresSetup, true);
  const logged = await request('/api/auth/login', { username: 'ordinary', password });
  assert.equal(logged.status, 200); assert.equal(logged.body.user.id, user.id);
  assert.equal(logged.body.token, undefined); assert.match(logged.headers.get('set-cookie'), /HttpOnly/);
  assert.match(logged.headers.get('set-cookie'), /Secure/); assert.match(logged.headers.get('set-cookie'), /SameSite=Lax/);
  const cookie = logged.headers.get('set-cookie').split(';')[0];
  const me = await request('/api/auth/me', undefined, { Cookie: cookie }); assert.equal(me.status, 200);
  assert.equal(me.headers.get('cache-control'), 'no-store'); assert.equal(typeof me.body.csrfToken, 'string');
  assert.equal((await request('/private?userId=forged', undefined, { Cookie: cookie, 'X-User-Id': admin.id })).body.userId, user.id);
  assert.equal((await request('/private', undefined, { 'X-Access-Password': password })).status, 401);
  assert.equal((await request('/private', undefined, { Cookie: `${cookie}; ${cookie}` })).status, 401);
  assert.equal((await request('/api/auth/logout', {}, { Cookie: cookie })).status, 403);
  assert.equal((await request('/api/auth/logout', {}, { Cookie: cookie, 'X-CSRF-Token': me.body.csrfToken })).status, 200);
  assert.equal((await request('/api/auth/me', undefined, { Cookie: cookie })).status, 401);

  const challenge = await request('/api/auth/login', { username: 'factor-user', password, ephemeral: true });
  assert.equal(challenge.body.requiresSecondFactor, true); assert.equal(challenge.headers.get('set-cookie'), null);
  assert.equal((await request('/api/auth/me', undefined, { Cookie: `__Host-dn_session=${challenge.body.challenge}` })).status, 401);
  const verified = await request('/api/auth/login/verify', { challenge: challenge.body.challenge, code: p.generateTotp(secret, { now: at }) });
  assert.equal(verified.status, 200); assert.doesNotMatch(verified.headers.get('set-cookie'), /Max-Age/);
  assert.equal((await request('/api/auth/login/verify', { challenge: challenge.body.challenge, code: p.generateTotp(secret, { now: at }) })).status, 401);
  const replayChallenge = await request('/api/auth/login', { username: 'factor-user', password });
  assert.equal((await request('/api/auth/login/verify', { challenge: replayChallenge.body.challenge, code: p.generateTotp(secret, { now: at }) })).status, 401);
  at += 30000;
  assert.equal((await request('/api/auth/login/verify', { challenge: replayChallenge.body.challenge, code: p.generateTotp(secret, { now: at }) })).status, 200);
  const locked = await request('/api/auth/login', { username: 'factor-user', password });
  for (let i = 0; i < 5; i += 1) assert.equal((await request('/api/auth/login/verify', { challenge: locked.body.challenge, code: 'bad' })).status, 401);
  at += 30000;
  assert.equal((await request('/api/auth/login/verify', { challenge: locked.body.challenge, code: p.generateTotp(secret, { now: at }) })).status, 401);
  const expiring = await request('/api/auth/login', { username: 'factor-user', password }); at += 300001;
  assert.equal((await request('/api/auth/login/verify', { challenge: expiring.body.challenge, code: p.generateTotp(secret, { now: at }) })).status, 401);
  assert.equal((await request('/api/auth', { password })).status, 410);
});
